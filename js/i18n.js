let lang = 'gu';
try { lang = localStorage.getItem('swf.lang') || 'gu'; } catch { /* ignore */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'gu';
  try { localStorage.setItem('swf.lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}
export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.gu[key] ?? key;
  if (vars && typeof s === 'string') for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
/** Pick the current-language text from {gu, en} content objects, falling back to Gujarati. */
export const tr = (obj) => (obj && (obj[lang] || obj.gu)) || '';
document.documentElement.lang = lang;
